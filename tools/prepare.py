"""Prepare GCam for the selected Floral base without editing other repositories."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

from fetch_prebuilts import ROOT, digest, verify_all
from integration import (DEFAULT_REPLACEMENTS, PACKAGE, SIGNER_SHA256, camera_policy,
                         certificate, policy_files, resolve_keys, vendor_dependencies)
from verify_payload import check_payload


def snapshot(paths):
    return [{"path": str(p.resolve()), "sha256": digest(p)}
            for p in sorted(set(paths))]


def make_path(path):
    value = str(path)
    if not re.fullmatch(r"[A-Za-z0-9_./+-]+", value):
        raise ValueError("Android Make integration requires paths without whitespace or Make metacharacters")
    return value


def prepare(rom, device, vendor, policy_dirs, aliases=None, replace_modules=None,
            services_module=None, root=ROOT, check_apks=True):
    rom, vendor, root = rom.resolve(), vendor.resolve(), root.resolve()
    policy_dirs = sorted(set(p.resolve() for p in policy_dirs))
    aliases = aliases or {}
    if device not in {"coral", "flame"}:
        raise ValueError("Select coral or flame")
    if not vendor.is_relative_to(rom) or vendor == rom:
        raise ValueError("--vendor-tree must be inside the ROM source root")
    if any(root == p or root.is_relative_to(p) for p in policy_dirs):
        raise ValueError("Select base policy directories, excluding this plugin's generated policy")
    for path in [rom, vendor, root, *policy_dirs, *aliases.values()]:
        make_path(path)
    verify_all(root)
    lock = json.loads((root / "prebuilts.lock.json").read_text())
    if lock["package"] != PACKAGE or lock["signer_sha256"] != SIGNER_SHA256:
        raise ValueError("Camera package/certificate lock changed")
    der = certificate(root / "configs/GoogleCamera.x509.pem")
    if hashlib.sha256(der).hexdigest() != SIGNER_SHA256:
        raise ValueError("Camera public certificate differs from the pinned Google signer")
    if check_apks:
        source = json.loads((root / "provenance/source.json").read_text())
        check_payload(root / "proprietary", source, (None, None),
                      root / "provenance/payload.json")
    paths = policy_files(policy_dirs)
    aliases = resolve_keys(rom, paths, aliases)
    policy = camera_policy(paths, aliases)
    base = vendor_dependencies(vendor, rom, services_module)
    for namespace in base["namespaces"]:
        make_path(namespace)
    for module in base["modules"]:
        if not module or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.+-]*", module):
            raise ValueError("Unsupported vendor dependency module name")
    replacements = sorted(set(DEFAULT_REPLACEMENTS + (replace_modules or [])))
    for module in replacements:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.+-]*", module):
            raise ValueError("Invalid replacement module name")
    if set(replacements) & ({"FloralGoogleCamera", "floral_gcam_apk_set"} | set(base["modules"])):
        raise ValueError("A required plugin/dependency module cannot be replaced")
    xml = ET.Element("policy")
    if policy["add_signer"]:
        signer = ET.SubElement(xml, "signer", signature=der.hex())
        package = ET.SubElement(signer, "package", name=PACKAGE)
        ET.SubElement(package, "seinfo", value="google")
    ET.indent(xml, space="    ")
    config = (
        "# Generated by tools/prepare.py; rerun preparation after base changes.\n"
        f"FLORAL_GCAM_DEVICE := {device}\n"
        f"FLORAL_GCAM_ADD_SIGNER := {str(policy['add_signer']).lower()}\n"
        "FLORAL_GCAM_REPLACED_MODULES := " + " ".join(replacements) + "\n"
        "FLORAL_GCAM_DEPENDENCY_MODULES := " + " ".join(base["modules"]) + "\n"
        "FLORAL_GCAM_VENDOR_NAMESPACES := " + " ".join(base["namespaces"]) + "\n"
    )
    # No write occurs until all base, certificate, APK and policy checks pass.
    generated = root / "generated"
    (generated / "sepolicy").mkdir(parents=True, exist_ok=True)
    outputs = {
        "Android.bp": (root / "Android.bp.in").read_text().replace(
            "@OVERRIDES@", json.dumps(replacements)),
        "generated/config.mk": config,
        "generated/sepolicy/mac_permissions.xml":
            '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(xml, encoding="unicode") + "\n",
    }
    for name, content in outputs.items():
        (root / name).write_text(content)
    own_inputs = [root / name for name in ["prebuilts.lock.json", "provenance/source.json",
                  "provenance/payload.json", "Android.bp.in", "gcam.mk", "BoardConfigGCam.mk"]]
    own_inputs += list((root / "configs").glob("*"))
    profile = {
        "schema": 1, "device": device, "plugin_root": str(root),
        "rom_root": str(rom), "vendor_tree": str(vendor),
        "policy_dirs": [str(p) for p in policy_dirs], "policy_files": [str(p) for p in paths],
        "vendor_blueprints": [str(p) for p in base["files"] if p.name == "Android.bp"],
        "input_files": snapshot(paths + base["files"] + own_inputs + list(aliases.values())),
        "output_files": [{"path": name, "sha256": digest(root / name)} for name in outputs],
        "policy": policy, "replaced_modules": replacements,
        "dependencies": base["modules"], "namespaces": base["namespaces"],
    }
    (generated / "profile.json").write_text(json.dumps(profile, indent=2) + "\n")
    print(f"Prepared Floral GCam for {device}; original Google signature retained.")
    print("Camera signer policy:", "add package-scoped mapping" if policy["add_signer"]
          else "reuse " + policy["signer_source"])
    return profile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom-root", type=Path, default=Path.cwd())
    parser.add_argument("--device", choices=["coral", "flame"], required=True)
    parser.add_argument("--vendor-tree", type=Path, required=True)
    parser.add_argument("--policy-dir", type=Path, action="append", required=True,
                        help="Every active base policy root; repeat as needed")
    parser.add_argument("--sepolicy-key", action="append", default=[], metavar="TAG=PUBLIC_CERT")
    parser.add_argument("--replace-module", action="append", default=[])
    parser.add_argument("--camera-services-module")
    args = parser.parse_args()
    try:
        rom = args.rom_root.resolve()
        def absolute(path):
            return (path if path.is_absolute() else rom / path).resolve()
        aliases = {}
        for value in args.sepolicy_key:
            tag, path = value.split("=", 1)
            if not re.fullmatch(r"[A-Za-z0-9_]+", tag) or tag in aliases:
                raise ValueError("Use distinct --sepolicy-key TAG=PUBLIC_CERT entries")
            aliases[tag] = absolute(Path(path))
        prepare(rom, args.device, absolute(args.vendor_tree),
                [absolute(p) for p in args.policy_dir], aliases, args.replace_module,
                args.camera_services_module)
    except (OSError, ValueError, ET.ParseError) as error:
        print("Floral GCam setup:", error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
